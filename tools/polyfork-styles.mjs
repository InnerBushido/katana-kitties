/* ---------------------------------------------------------------------------
   POLYFORK STYLES -> src/systems/housing/modelstyles.js (GENERATED)

   `node tools/polyfork-styles.mjs` — needs the network, once; the game never.

   A Polyfork asset's colour knobs ("colorway", "glaze", ...) are not baked
   into separate files: the vendored GLB carries the DEFAULT preset's hexes in
   COLOR_0, and every other preset is the same zones repainted. So a style is
   a palette swap — find each zone's default colour in the vertex colours and
   write the preset's colour in its place — which the game can do with the
   file it already has and nothing else (models.js `styleModel`).

   Geometry knobs (a katana's length, a tsuba's shape) WOULD need a baked file
   per option and are left out: see docs/notes/housing.md, Item customization.

   Reads each vendored file's params.json from polyfork.dev/cdn — the public,
   key-free JSON next to the free models. No key is needed or read.
--------------------------------------------------------------------------- */
import { readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../public/models/polyfork/', import.meta.url);
const ids = readdirSync(dir).filter((f) => /-[0-9a-f]{6}\.glb$/.test(f)).map((f) => f.slice(0, -4));
const out = {};
for (const id of ids) {
  const r = await fetch(`https://polyfork.dev/cdn/${id}-params.json`);
  if (!r.ok) { console.log(id.padEnd(36), 'no params', r.status); continue; }
  const P = await r.json();
  const presets = P.presets ?? {};
  // the choice knob whose options ARE the presets, and its default
  const knob = Object.entries(P.params ?? {}).find(([, v]) => v.type === 'choice' && v.affects !== 'geometry'
    && (v.options ?? []).every((o) => presets[o]));
  if (!knob) { console.log(id.padEnd(36), 'no colour presets'); continue; }
  const [name, k] = knob;
  const def = presets[k.default];
  // the default first: it is the one the file already is, and "as it came"
  const order = [k.default, ...k.options.filter((o) => o !== k.default)];
  const styles = order.map((o) => ({
    id: o,
    // only the zones that actually change, as [from, to]
    swap: Object.keys(def).filter((z) => presets[o][z] && presets[o][z].toLowerCase() !== def[z].toLowerCase())
      .map((z) => [def[z].toLowerCase(), presets[o][z].toLowerCase()]),
  }));
  out[id] = { knob: k.label ?? name, styles };
  console.log(id.padEnd(36), name, k.options.join(' / '));
}
const body = `/* GENERATED by tools/polyfork-styles.mjs — do not edit by hand.
   Each vendored Polyfork model's colour presets, as palette swaps over the
   default build's vertex colours (models.js \`styleModel\`). */
export const MODEL_STYLES = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(new URL('../src/systems/housing/modelstyles.js', import.meta.url), body.replace(/\n/g, '\r\n'));
console.log('wrote', Object.keys(out).length, 'models');
