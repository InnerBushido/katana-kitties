#!/usr/bin/env node
/**
 * THE ISLAND JUKEBOX'S RECORDINGS — from the raw takes to what the game plays.
 *
 *   node tools/capture/jukebox-music.mjs           measure, loop, write it all
 *   node tools/capture/jukebox-music.mjs --dry     measure and print; write nothing
 *
 * The takes are ElevenLabs Music v2.5, one per track in housing/jukebox.js
 * (whose `prompt` is what each was asked for — pre-authorised for Custom
 * Housing, Oct 2026). Raw files live in `music-takes/jukebox/<id>.mp3` so this
 * can be re-run; `JUKEBOX` there is the list, so a track with no take is
 * simply left out and keeps its procedural fallback.
 *
 * THE SAME LOOP AS THE BOSS MUSIC, from music-loop.mjs: the beat is measured,
 * a loop is found by self-similarity on whole bars, the seam is aligned and
 * cut in the gap before the beat, and the level is matched to the procedural
 * pieces. What differs is only the tempo band the beat search is held to: a
 * jukebox runs 70 to 140 BPM against the boss's fixed 136, and an unbounded
 * search locks onto 3/2 of the beat (audio.md). So each take is searched in
 * ±12% of the BPM its prompt asked for — and if a take ignored its prompt,
 * the loop is still whole bars of SOMETHING, which is all a jukebox needs.
 *
 * WRITES public/music/<id>.mp3 (the take as it came, not re-encoded) and
 * src/systems/housing/jukeboxfiles.js. Generated: do not edit it by hand.
 */
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { measure } from './music-beats.mjs';
import { decodeStereo, beatFeatures, findLoop, bandOnsets, seamLag, seamCut, rmsOf } from './music-loop.mjs';
import { JUKEBOX } from '../../src/systems/housing/jukebox.js';

const ROOT = new URL('../../', import.meta.url);
const P = (rel) => fileURLToPath(new URL(rel, ROOT));
const RAW = 'tools/capture/music-takes/jukebox/';
/** The procedural pieces' level — the same target shadow-music.mjs uses. */
const TARGET_RMS = 0.050;
/** Generation ids, so a take can be found again in the ElevenLabs flow (LRBTaBnKWB4SFA1bf00O). */
const GEN = {
  homeSurf: 'UlhLAZmaw21kO5rXg3gR',
  homeLofi: '3Av8rFoBYAstga0olNDd',
  homeFestival: '93hgtbyRJ6FFBBQxlyr4',
  homeGarden: 'g8RoUUalOEMy5JyMHp4h',
  homeChiptune: 'U4TriowQSrbwFULdbQuA',
  homeSunset: '9Vq5ndYiki2lSoDDWkzs',
};

const dry = process.argv.includes('--dry');
const meta = {};
mkdirSync(P('public/music'), { recursive: true });
for (const T of JUKEBOX) {
  const src = P(`${RAW}${T.id}.mp3`);
  if (!existsSync(src)) { console.log(`${T.id}: no take in ${RAW} — stays procedural (${T.fallback})`); continue; }
  const bpm = +(/(\d+)\s*bpm/i.exec(T.prompt)?.[1] ?? 100);
  const spb = 60 / bpm;
  const m = measure(src, [spb / 1.12, spb * 1.12]);
  const st = decodeStereo(src);
  const mono = st.L.map((v, i) => 0.5 * (v + st.R[i]));
  const beatsEnd = Math.floor((m.soundEnd - m.firstBeat) / m.spb);
  const f = beatFeatures(mono, m.firstBeat, m.spb, beatsEnd);
  const { best, top5 } = findLoop(f, beatsEnd);
  const tA = m.firstBeat + best.A * m.spb;
  const tB = m.firstBeat + best.B * m.spb;
  const { lag, corr } = seamLag(bandOnsets(mono), tA, tB, m.spb);
  const off = seamCut(mono, tA + lag, tB);
  const cutA = tA + lag + off, cutB = tB + off;
  const rms = rmsOf(mono, tA, tB);
  console.log(`${T.id}: asked ${bpm} BPM, measured ${m.bpm}, first beat ${m.firstBeat}s, drift span ${m.driftSpan}ms`);
  console.log(`  loop beats ${best.A}-${best.B} (${(tB - tA).toFixed(2)}s), score ${best.score.toFixed(3)}; top: ${top5.map((c) => `${c.A}-${c.B}:${c.score.toFixed(3)}`).join(' ')}`);
  console.log(`  seam lag ${(lag * 1000).toFixed(0)}ms (corr ${corr.toFixed(3)}), cut ${cutA.toFixed(4)}s -> ${cutB.toFixed(4)}s, RMS ${rms.toFixed(4)} -> mix ${(TARGET_RMS / rms).toFixed(2)}`);
  meta[T.id] = {
    file: `music/${T.id}.mp3`, name: T.name, level: 'home', gen: GEN[T.id] ?? null,
    spb: m.spb, first: m.firstBeat, beats: Math.floor(beatsEnd / 4) * 4,
    loop: [+cutA.toFixed(4), +cutB.toFixed(4)], loopBeats: [best.A, best.B],
    lag: +lag.toFixed(3), mix: +(TARGET_RMS / rms).toFixed(3), drift: m.driftSpan,
  };
  if (!dry) copyFileSync(src, P(`public/${meta[T.id].file}`));
}
if (!dry) {
  writeFileSync(P('src/systems/housing/jukeboxfiles.js'), `/* GENERATED by tools/capture/jukebox-music.mjs — do not edit; re-run it.\r
   The island jukebox's recordings, MEASURED the way the boss music is (see\r
   src/core/musicfiles.js): beat, first beat, the loop, and the gain to the\r
   procedural level. A track missing here plays its procedural fallback. */\r
export const JUKEBOX_FILES = ${JSON.stringify(meta, null, 2).replace(/\n/g, '\r\n')};\r
`);
  console.log('wrote src/systems/housing/jukeboxfiles.js');
}
